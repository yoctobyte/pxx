#!/bin/sh
# record.sh: write the Limine recipe that onsite.sh replays on the target.
#
# Limine 12.11.1 (BSD-2-Clause; the third-party code in its binaries is 0BSD,
# MIT, BSD-2, Apache-2.0, CC0 and CC-BY: 3RDPARTY.md, installed with them).
# What pxx builds on site is the `limine` host tool (one C file, limine.c:
# bios-install, enroll-config, --print-datadir). The boot loaders themselves
# (limine-bios.sys, the stage-1 sectors, BOOTX64.EFI and the other UEFI
# images, the CD/PXE images) SHIP AS THE RELEASE'S BINARIES, from the signed
# limine-binary tarball, because building them takes what the target does not
# have and pxx is not:
#   - nasm: 35 assembler files (stage 1 for HDD/CD/PXE, the real-mode and
#     protected-mode entry, the EFI and menu thunks, SMP spin-up), in nasm
#     syntax, which pxx's inline-asm encoder does not read;
#   - a freestanding cross toolchain per port (-m32 -march=i686 -fno-PIC for
#     BIOS, -fPIE PE for UEFI, aarch64/riscv64/loongarch64), with ld.lld or
#     GNU ld driven by six linker scripts (section placement, stage-2 split,
#     symbol tables generated by gensyms.sh with nm);
#   - objcopy: -O binary for the BIOS stages, the build-id note turned into
#     an object, and the ELF-to-PE conversion for every .EFI;
#   - real-mode i386 code, which pxx does not generate.
# The tool is limine.c from limine-binary (identical to the source tarball's
# host/limine.c with the release's version strings filled in) and its
# limine-bios-hdd.h, the HDD stage-1 sectors as a byte array.
# Nothing is configured or generated, so record.sh only pins the tarball.
#
#   NODISX_WORK=/data/tmp/nodisx tools/nodisx/limine/record.sh
set -eu
T=$(cd "$(dirname "$0")" && pwd)
W=${NODISX_WORK:?set NODISX_WORK to a work directory}
TARBALL=limine-binary-12.11.1.tar.xz
"$T/../fetch.sh" "$TARBALL" > /dev/null
R=$W/recipe/limine
rm -rf "$R"
mkdir -p "$R"
echo "$TARBALL $(sha256sum "$W/dl/$TARBALL" | cut -d' ' -f1)" > "$R/sources.list"
cp "$T/onsite.sh" "$R/onsite.sh"
git -C "$T" rev-parse HEAD > "$R/RECIPE" 2>/dev/null || echo unknown > "$R/RECIPE"
echo "recipe: $R (limine.c built by pxx; boot loaders ship as the release's binaries)"
