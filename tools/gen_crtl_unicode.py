#!/usr/bin/env python3
"""Generate lib/crtl/src/wchar_unicode.inc -- crtl's C.UTF-8 character tables.

WHERE THE DATA COMES FROM. glibc's own C.UTF-8 locale, read through its public
functions (iswalpha .. iswalnum, wcwidth, towlower, towupper) for every code
point 0..0x10FFFF, by a small C program this script compiles with the host gcc
and runs. gcc/glibc is the reference crtl is measured against, so the tables
are glibc's answers rather than an independent reading of the Unicode data
files, and test/c_crtl_utf8_locale.c checks them whole (a hash over every
code point) against the same glibc. The glibc version is recorded in the
output. Regenerating on a newer glibc moves the tables to its Unicode version.

WHAT IT WRITES, and why this shape:
  - __u8_start[] / __u8_props[]: ranges of code points with the same 12 class
    bits and wcwidth, found by binary search. Bits 0..11 are the classes in
    the order CLASS_NAMES below; bits 12..13 are wcwidth + 1 (0..3).
  - __u8_lo_* / __u8_up_*: towlower and towupper as runs. A run is `n` code
    points from `start` in steps of `stride` (1 or 2) that all map by the same
    `delta`. Most of Unicode's case pairs alternate upper/lower, so stride 2
    turns hundreds of single mappings into one run.

Usage: python3 tools/gen_crtl_unicode.py [--check]
"""
import os
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "lib", "crtl", "src", "wchar_unicode.inc")

CLASS_NAMES = ["alpha", "digit", "blank", "cntrl", "graph", "print",
               "lower", "upper", "punct", "space", "xdigit", "alnum"]

EXTRACTOR = r"""
#define _GNU_SOURCE
#include <locale.h>
#include <stdio.h>
#include <wchar.h>
#include <wctype.h>
#include <gnu/libc-version.h>
int main(void) {
  wint_t c;
  if (!setlocale(LC_ALL, "C.UTF-8")) { fprintf(stderr, "no C.UTF-8\n"); return 1; }
  printf("glibc %s\n", gnu_get_libc_version());
  for (c = 0; c <= 0x10FFFF; c++) {
    unsigned k = (iswalpha(c) ? 1 : 0) | (iswdigit(c) ? 2 : 0) | (iswblank(c) ? 4 : 0) |
      (iswcntrl(c) ? 8 : 0) | (iswgraph(c) ? 16 : 0) | (iswprint(c) ? 32 : 0) |
      (iswlower(c) ? 64 : 0) | (iswupper(c) ? 128 : 0) | (iswpunct(c) ? 256 : 0) |
      (iswspace(c) ? 512 : 0) | (iswxdigit(c) ? 1024 : 0) | (iswalnum(c) ? 2048 : 0);
    int w = wcwidth((wchar_t)c);
    printf("%u %d %ld %ld\n", k, w, (long)towlower(c) - (long)c, (long)towupper(c) - (long)c);
  }
  return 0;
}
"""


def extract():
    with tempfile.TemporaryDirectory() as d:
        src = os.path.join(d, "x.c")
        exe = os.path.join(d, "x")
        open(src, "w").write(EXTRACTOR)
        subprocess.check_call(["gcc", "-O2", "-o", exe, src])
        out = subprocess.check_output([exe]).decode().split("\n")
    version = out[0]
    rows = [tuple(int(x) for x in line.split()) for line in out[1:] if line]
    assert len(rows) == 0x110000, len(rows)
    return version, rows


def case_runs(deltas):
    """[(start, n, stride, delta)] covering every code point whose delta != 0."""
    runs = []
    for c, d in enumerate(deltas):
        if d == 0:
            continue
        if runs:
            s, n, st, dl = runs[-1]
            last = s + (n - 1) * st
            if dl == d:
                if n == 1 and c - s in (1, 2):
                    runs[-1] = (s, 2, c - s, dl)
                    continue
                if n > 1 and c == last + st:
                    runs[-1] = (s, n + 1, st, dl)
                    continue
        runs.append((c, 1, 1, d))
    return runs


def fmt_array(ctype, name, values, per_line=10):
    lines = []
    for i in range(0, len(values), per_line):
        lines.append("  " + ", ".join(str(v) for v in values[i:i + per_line]) + ",")
    return "static const %s %s[%d] = {\n%s\n};\n" % (ctype, name, len(values), "\n".join(lines))


def generate():
    version, rows = extract()
    starts, props = [], []
    prev = None
    for c, (k, w, _, _) in enumerate(rows):
        assert -1 <= w <= 2, (c, w)
        p = k | ((w + 1) << 12)
        if p != prev:
            starts.append(c)
            props.append(p)
            prev = p
    lo = case_runs([r[2] for r in rows])
    up = case_runs([r[3] for r in rows])
    out = []
    out.append("/* GENERATED by tools/gen_crtl_unicode.py from %s's C.UTF-8 -- DO NOT EDIT.\n"
               "   %d property ranges, %d tolower runs, %d toupper runs.\n"
               "   Property bits 0..11: %s; bits 12..13: wcwidth + 1. */\n"
               % (version, len(starts), len(lo), len(up), " ".join(CLASS_NAMES)))
    out.append("#define __U8_NPROPS %d\n" % len(starts))
    out.append(fmt_array("unsigned int", "__u8_start", starts))
    out.append(fmt_array("unsigned short", "__u8_props", props))
    for tag, runs in (("lo", lo), ("up", up)):
        out.append("#define __U8_N%s %d\n" % (tag.upper(), len(runs)))
        out.append(fmt_array("unsigned int", "__u8_%s_start" % tag, [r[0] for r in runs]))
        out.append(fmt_array("unsigned short", "__u8_%s_n" % tag, [r[1] for r in runs]))
        out.append(fmt_array("unsigned char", "__u8_%s_stride" % tag, [r[2] for r in runs], 20))
        out.append(fmt_array("int", "__u8_%s_delta" % tag, [r[3] for r in runs]))
    return "\n".join(out)


def main():
    text = generate()
    if "--check" in sys.argv[1:]:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        if cur != text:
            print("lib/crtl/src/wchar_unicode.inc is stale: run python3 tools/gen_crtl_unicode.py")
            return 1
        return 0
    open(OUT, "w").write(text)
    print("wrote", os.path.relpath(OUT, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
